// ? HTTP request/response cycle
// It's a conversation between user, client (browser, app) and server
// User sends http request message to the server, and server responds with http response message

// HTTP Methods, HTTP Request (Client → Server):
// - GET: read data
// - POST: send data
// - PUT/PATH: update data
// - DELETE: remove data

// STATUS CODES:
// - 200: OK (successful)
// - 201: created
// - 404: Not Found
// - 500: Server Error