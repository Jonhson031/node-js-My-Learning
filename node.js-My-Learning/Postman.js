/* 🧪 // ? What is Postman?

Postman is a tool to test HTTP APIs without needing a frontend.

It lets you:

    - Send HTTP requests

    - Inspect responses

    - Test headers, body, status codes

    - Debug backend logic fast


? Think of it as a fake frontend for your backend.

🧠 Why Postman is important

    - When you build an API:

    - There is no UI yet

    - Browser can only easily do GET

    - You need to test POST, PUT, DELETE, auth, headers, etc.

👉 Postman solves that.

? 📡 What can you send with Postman?

    - HTTP methods: GET, POST, PUT, PATCH, DELETE

    - Query strings

    - Headers (Authorization, Content-Type)

    - Request body (JSON, form-data)

    - Cookies

    - Auth tokens (JWT, Bearer)*/